#!/usr/bin/env node
// Writes native/computer-use-macos/licenses/agent-desktop-crates.txt: every
// Rust crate the vendored agent-desktop binary (native/agent-desktop) builds
// from, with its license expression and the license files it publishes,
// verbatim. scripts/generate-notices.mjs folds the file into
// THIRD_PARTY_NOTICES.
//
//   node scripts/gen-agent-desktop-crates.mjs
//
// Needs cargo and the crates fetched (`cargo fetch --locked` in
// native/agent-desktop). The list is the union over every target in
// Cargo.lock, not just the host's, so the committed file, and the notices
// check built on it, are the same on every OS. Run it again whenever the
// vendored tree is updated.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'native/agent-desktop');
const OUT = join(ROOT, 'native/computer-use-macos/licenses/agent-desktop-crates.txt');
const LICENSE_FILE = /^(licen[cs]e|copying|notice|unlicense)/i;

const metadata = JSON.parse(execFileSync('cargo', ['metadata', '--format-version', '1', '--locked'], { cwd: SRC, maxBuffer: 64 << 20 }).toString());
const packages = new Map(metadata.packages.map((p) => [p.id, p]));
const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]));
const root = metadata.packages.find((p) => p.name === 'agent-desktop' && p.source === null);
if (!root) throw new Error('agent-desktop is not a package of native/agent-desktop');

// Everything the binary is built from: normal and build dependencies, never dev.
const used = new Set();
const stack = [root.id];
while (stack.length > 0) {
  const id = stack.pop();
  if (used.has(id)) continue;
  used.add(id);
  for (const dep of nodes.get(id).deps) {
    if (dep.dep_kinds.some((k) => k.kind !== 'dev')) stack.push(dep.pkg);
  }
}

const crates = [...used]
  .map((id) => packages.get(id))
  .filter((p) => p.source !== null)
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const lf = (s) => s.replace(/\r\n?/g, '\n');
const printed = new Map();
const out = [
  'Rust crates compiled into agent-desktop',
  '',
  `Generated by scripts/gen-agent-desktop-crates.mjs from native/agent-desktop/Cargo.lock`,
  `(${crates.length} crates, every target). Each license file is reproduced verbatim from the`,
  'published crate; a text that already appeared above is named instead of repeated.',
  '',
];
for (const crate of crates) {
  out.push('-'.repeat(78));
  out.push(`${crate.name} ${crate.version}`);
  out.push(`License: ${crate.license ?? crate.license_file ?? 'not declared'}`);
  if (crate.repository) out.push(`Source: ${crate.repository}`);
  const dir = dirname(crate.manifest_path);
  const files = readdirSync(dir).filter((f) => LICENSE_FILE.test(f)).sort();
  if (files.length === 0) out.push('(The published crate carries no license file.)');
  for (const file of files) {
    const text = lf(readFileSync(join(dir, file), 'utf8')).trimEnd();
    const hash = createHash('sha256').update(text).digest('hex');
    const first = printed.get(hash);
    if (first) {
      out.push(`${file}: same text as ${first}`);
      continue;
    }
    printed.set(hash, `${crate.name} ${crate.version} ${file}`);
    out.push('');
    out.push(`--- ${file} ---`);
    out.push(text);
  }
  out.push('');
}
writeFileSync(OUT, `${out.join('\n').trimEnd()}\n`);
console.log(`wrote ${OUT}: ${crates.length} crates, ${printed.size} distinct license texts`);
